"""
Group orders and generator reduction for Task B through Oscar/GAP, in place of a
randomized Schreier–Sims.
"""
module FTShadowsOscarExt

using FTShadows, Oscar

const TB = FTShadows.TaskB

function _recog_loaded()
    GAP.Globals.LoadPackage(GAP.Obj("recog"); on_load_error=false) || error("GAP package recog not available")
    return true
end

_gapgroup(gens) = GapObj(matrix_group([matrix(GF(2), Int.(g)) for g in gens]))

"""
    group_order(gens, d; method=:recog)

Order of ⟨gens⟩ ⊂ GL(d, 2) as a `BigInt`. `method=:recog` uses GAP's `recog` package (about 1 s even for the
gross group of order 11,324,620,800, where GAP's default nice monomorphism on the 2^24 vectors does not finish);
`method=:oscar` uses Oscar's `order`.
"""
function TB.group_order(gens, d::Integer; method::Symbol=:recog)
    isempty(gens) && return big(1)
    all(g -> size(g) == (d, d), gens) || throw(DimensionMismatch("generators must be $d × $d"))
    method == :oscar && return BigInt(order(matrix_group([matrix(GF(2), Int.(g)) for g in gens])))
    _recog_loaded()
    ri = GAP.Globals.RecognizeGroup(_gapgroup(gens))
    return BigInt(GAP.gap_to_julia(GAP.Globals.Size(ri)))
end

"""
    reduce_generators(mats, d) -> (kept, order)

Keep a matrix only if it is not in the group generated by the matrices kept before it (duplicates dropped
first). Membership is tested with the recognition tree of the current group (`SLPforElement` and evaluation),
so the kept list is the one an exact Schreier–Sims would give, in input order.
"""
function TB.reduce_generators(mats, d::Integer)
    _recog_loaded()
    uniq = TB.GF2Mat[]
    for m in mats
        TB.GF2Mat(m) in uniq || push!(uniq, TB.GF2Mat(m))
    end
    kept = [uniq[1]]
    ri = GAP.Globals.RecognizeGroup(_gapgroup(kept))
    for m in uniq[2:end]
        x = GAP.Globals.GeneratorsOfGroup(_gapgroup([m]))[1]
        slp = GAP.Globals.SLPforElement(ri, x)
        if slp !== GAP.Globals.fail &&
           GAP.Globals.ResultOfStraightLineProgram(slp, GAP.Globals.NiceGens(ri)) == x
            continue
        end
        push!(kept, m)
        ri = GAP.Globals.RecognizeGroup(_gapgroup(kept))
    end
    return kept, BigInt(GAP.gap_to_julia(GAP.Globals.Size(ri)))
end

end
