# Shadow channel of the native ensemble "uniform g in G, random logical Pauli frame, destructive readout".
#
# λ_P = Pr_g[g P g† is Z-type] (X-type for all-X readout), ||P||² = 1/λ_P (Bu et al. 2202.03272, Prop. 3). For
# uniform g, g(P) is uniform on the orbit of P, so λ^Z_P = |orbit(P) ∩ Z-type| / |orbit(P)|.
#
# Several helpers below copy numpy's floating-point behaviour on purpose (pairwise summation, np.round), so the
# Julia records equal the saved ones bit for bit.

"""
    pauli_masks(k) -> (xmask, zmask)

Bit masks of the X part and of the Z part of a packed logical Pauli.
"""
pauli_masks(k::Integer) = (UInt32(1) << k - UInt32(1), (UInt32(1) << k - UInt32(1)) << k)

"""
    logical_weights(k)

Weight (number of non-identity qubits) of every packed logical Pauli on k qubits, indexed by v + 1.
"""
function logical_weights(k::Integer)
    xmask, _ = pauli_masks(k)
    return Int8[count_ones((v & xmask) | (v >> k)) for v in UInt32(0):UInt32((1 << 2k) - 1)]
end

"""
    lambdas_from_labels(lab, k) -> (λ_Z, λ_X, orbit_size)

λ^Z, λ^X and the orbit size of every packed logical Pauli from orbit labels (λ of the identity set to 1).
"""
function lambdas_from_labels(lab::AbstractVector{UInt32}, k::Integer)
    n = length(lab)
    xmask, zmask = pauli_masks(k)
    size_ = zeros(Int, n)
    zc = zeros(Int, n)
    xc = zeros(Int, n)
    @inbounds for i in 1:n
        v = UInt32(i - 1)
        l = lab[i] + 1
        size_[l] += 1
        v != 0 && v & xmask == 0 && (zc[l] += 1)
        v != 0 && v & zmask == 0 && (xc[l] += 1)
    end
    fz = [s > 0 ? zc[i] / s : 0.0 for (i, s) in enumerate(size_)]
    fx = [s > 0 ? xc[i] / s : 0.0 for (i, s) in enumerate(size_)]
    lam_z = fz[lab.+1]
    lam_x = fx[lab.+1]
    lam_z[1] = lam_x[1] = 1.0
    return lam_z, lam_x, size_[lab.+1]
end

"""
    channel_for_group(gens, k) -> (λ_Z, λ_X, orbit_size, labels)

Shadow-channel eigenvalues of the group generated by `gens` (no generators: the trivial group).
"""
function channel_for_group(gens, k::Integer)
    lab = isempty(gens) ? collect(UInt32(0):UInt32((1 << 2k) - 1)) : orbits(gens, 2k)
    return (lambdas_from_labels(lab, k)..., lab)
end

"""
    np_sum(x)

Sum with numpy's pairwise summation (blocks of 128, 8 accumulators), so float totals match numpy exactly.
"""
function np_sum(x::AbstractVector{Float64})
    function pw(lo, n)
        if n < 8
            r = 0.0
            for i in lo:lo+n-1
                r += x[i]
            end
            return r
        elseif n <= 128
            r = x[lo:lo+7]
            i = 8
            while i < n - n % 8
                for j in 1:8
                    r[j] += x[lo+i+j-1]
                end
                i += 8
            end
            res = ((r[1] + r[2]) + (r[3] + r[4])) + ((r[5] + r[6]) + (r[7] + r[8]))
            while i < n
                res += x[lo+i]
                i += 1
            end
            return res
        else
            n2 = n ÷ 2
            n2 -= n2 % 8
            return pw(lo, n2) + pw(lo + n2, n - n2)
        end
    end
    return 0.0 + pw(firstindex(x), length(x))
end

np_mean(x::AbstractVector{Float64}) = np_sum(x) / length(x)
np_mean(x::AbstractVector{Bool}) = count(x) / length(x)

function np_median(x::AbstractVector{Float64})
    s = sort(x)
    n = length(s)
    return isodd(n) ? s[n÷2+1] : (s[n÷2] + s[n÷2+1]) / 2
end

"""
    np_round(x, decimals)

numpy's `np.round` for floats: `rint(x * 10^d) / 10^d`.
"""
np_round(x::Float64, d::Integer) = round(x * 10.0^d) / 10.0^d

"""
    py_round(x, ndigits)

Python's `round(float, ndigits)`: the correctly rounded decimal, read back as the nearest double.
"""
py_round(x::Float64, nd::Integer) = parse(Float64, Printf.format(Printf.Format("%.$(nd)f"), x))

"""
    pyfmt_g(x, prec=6)

Python's `f"{x:.6g}"`.
"""
pyfmt_g(x::Float64, prec::Integer=6) = Printf.format(Printf.Format("%.$(prec)g"), x)

"""
    weight_table(lam, weights, k; max_w=k, groups=nothing)

Per-weight statistics of λ (identity excluded), one `Dict` per weight with the keys of the stored table.
`groups` may hold precomputed index sets per weight.
"""
function weight_table(lam::AbstractVector{Float64}, weights::AbstractVector, k::Integer;
                      max_w::Integer=k, groups=nothing)
    rows = OrderedDict{String,Any}[]
    for w in 1:max_w
        sel = groups === nothing ? findall(==(w), weights) : groups[w]
        lw = lam[sel]
        learn = lw .> 0
        norms = 1.0 ./ lw[learn]
        row = OrderedDict{String,Any}(
            "weight" => w,
            "n_paulis" => length(sel),
            "n_learnable" => count(learn),
            "frac_learnable" => np_mean(learn),
            "local_pauli_norm2" => 3^w,
            "global_clifford_norm2" => 2^k + 1,
        )
        if any(learn)
            row["norm2_min"] = minimum(norms)
            row["norm2_median"] = np_median(norms)
            row["norm2_max"] = maximum(norms)
            row["norm2_mean"] = np_mean(norms)
            row["frac_learnable_beating_local"] = np_mean([l > 0 && 1.0 / l < 3^w for l in lw])
            rounded = sort(np_round.(norms, 9))
            hist = OrderedDict{String,Int}()
            for v in unique(rounded)
                hist[pyfmt_g(v)] = count(==(v), rounded)   # a later value with the same label wins, as in a Python dict
            end
            row["norm2_histogram"] = hist
        end
        push!(rows, row)
    end
    return rows
end

"""
    type_breakdown(lam, k)

Learnability split into pure-X, pure-Z and mixed logical Paulis.
"""
function type_breakdown(lam::AbstractVector{Float64}, k::Integer)
    xmask, zmask = pauli_masks(k)
    out = OrderedDict{String,Any}()
    for (name, f) in (("pure_X", v -> v & xmask != 0 && v & zmask == 0),
                      ("pure_Z", v -> v & zmask != 0 && v & xmask == 0),
                      ("mixed", v -> v & xmask != 0 && v & zmask != 0))
        sel = [f(UInt32(i - 1)) for i in eachindex(lam)]
        lw = lam[sel]
        out[name] = OrderedDict{String,Any}("n" => count(sel), "n_learnable" => count(>(0), lw),
                                     "frac_learnable" => np_mean(lw .> 0))
    end
    return out
end

const MAXW_TABLE = 4

const SHADOW_CSV_COLUMNS = ["code", "ensemble", "order", "readout", "weight", "n_paulis", "n_learnable",
    "frac_learnable", "norm2_min", "norm2_median", "norm2_max", "norm2_mean", "local_pauli_norm2",
    "global_clifford_norm2", "frac_beating_local_pauli"]

"""
    shadow_map(name, k, basis, generators, orders, descriptions) -> (record, csv_rows, lambda_mix)

The native-ensemble shadow map of one code: the `shadow_<code>.json`
record, the rows of `shadow_<code>_by_weight.csv` and the `Float32` λ_mix array of every ensemble.
`generators` maps ensemble name to its kept logical generators (ensembles in [`ENSEMBLES`](@ref) order).
"""
function shadow_map(name, k::Integer, basis, generators::AbstractDict, orders::AbstractDict, descriptions::AbstractDict)
    wts = logical_weights(k)
    groups = [findall(==(w), wts) for w in 1:k]
    out = OrderedDict{String,Any}("code" => name, "k" => k, "basis" => basis, "ensembles" => OrderedDict{String,Any}())
    csv_rows = OrderedDict{String,Any}[]
    lambda_mix = OrderedDict{String,Vector{Float32}}()
    for ename in ENSEMBLES
        lam_z, lam_x, _, lab = channel_for_group(generators[ename], k)
        ens = OrderedDict{String,Any}("order" => orders[ename], "n_nontrivial_orbits" => length(unique(lab)) - 1,
                               "description" => descriptions[ename], "readouts" => OrderedDict{String,Any}())
        mix = 0.5 .* (lam_z .+ lam_x)
        for (ro, lam) in (("Z", lam_z), ("X", lam_x), ("mix", mix))
            tab = weight_table(lam, wts, k; groups)
            allw = lam[2:end]
            learn = allw .> 0
            norms = 1.0 ./ allw[learn]
            ens["readouts"][ro] = OrderedDict{String,Any}(
                "by_weight" => tab[1:MAXW_TABLE],
                "all_weights" => OrderedDict{String,Any}(
                    "n_paulis" => length(allw), "n_learnable" => count(learn), "frac_learnable" => np_mean(learn),
                    "norm2_min" => minimum(norms), "norm2_median" => np_median(norms),
                    "norm2_max" => maximum(norms), "sum_lambda" => np_sum(allw)),
                "learnable_by_weight_all" => [OrderedDict{String,Any}("weight" => r["weight"],
                    "frac_learnable" => r["frac_learnable"], "norm2_median" => get(r, "norm2_median", nothing),
                    "norm2_max" => get(r, "norm2_max", nothing)) for r in tab],
                "type_breakdown" => type_breakdown(lam, k),
            )
            for r in tab[1:MAXW_TABLE]
                push!(csv_rows, OrderedDict{String,Any}(
                    "code" => name, "ensemble" => ename, "order" => ens["order"], "readout" => ro,
                    "weight" => r["weight"], "n_paulis" => r["n_paulis"], "n_learnable" => r["n_learnable"],
                    "frac_learnable" => r["frac_learnable"], "norm2_min" => get(r, "norm2_min", ""),
                    "norm2_median" => get(r, "norm2_median", ""), "norm2_max" => get(r, "norm2_max", ""),
                    "norm2_mean" => get(r, "norm2_mean", ""), "local_pauli_norm2" => r["local_pauli_norm2"],
                    "global_clifford_norm2" => r["global_clifford_norm2"],
                    "frac_beating_local_pauli" => get(r, "frac_learnable_beating_local", 0.0)))
            end
        end
        out["ensembles"][ename] = ens
        lambda_mix[ename] = Float32.(mix)
    end
    return out, csv_rows, lambda_mix
end

const PAULI_LETTER = OrderedDict((true, false) => "X", (false, true) => "Z", (true, true) => "Y")

"""
    weight1_detail(lambda_mix, k=12)

Unlearnable single-qubit logical Paulis and the distinct ||P||² (rounded to 3 decimals) of the learnable ones,
from a `Float32` λ_mix table.
"""
function weight1_detail(lam::AbstractVector{Float32}, k::Integer=12)
    w = logical_weights(k)
    xmask, _ = pauli_masks(k)
    un = String[]
    for i in findall(i -> w[i] == 1 && lam[i] == 0, eachindex(lam))
        v = UInt32(i - 1)
        x, z = v & xmask, v >> k
        q = 32 - leading_zeros(x | z)
        push!(un, PAULI_LETTER[(x > 0, z > 0)] * string(q))
    end
    vals = sort!(unique([py_round(Float64(1.0f0 / lam[i]), 3) for i in eachindex(lam) if w[i] == 1 && lam[i] > 0]))
    return OrderedDict{String,Any}("unlearnable_weight1" => un, "weight1_norm2_values" => vals)
end
