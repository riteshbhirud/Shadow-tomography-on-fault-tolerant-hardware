# Matrix groups over GF(2) acting on packed logical Pauli vectors (row convention v -> v M).
#
# Packing: bit j of the integer is coordinate j (0-based); coordinates 0..k-1 are the X part,
# k..2k-1 the Z part. The Pauli with packed value v sits at index v + 1 of every 4^k-long array, which is the
# order of the saved lambda_mix_*.npy files.

"""
    pack_rows(m)

Each 0/1 row of `m` packed into a `UInt64` (bit j = column j+1).
"""
pack_rows(m::AbstractMatrix) = [reduce(|, (UInt64(m[i, j]) << (j - 1) for j in axes(m, 2)); init=UInt64(0)) for i in axes(m, 1)]

"""
    unpack_rows(packed, width)

Inverse of [`pack_rows`](@ref).
"""
unpack_rows(packed::AbstractVector, width::Integer) = GF2Mat([(p >> (j - 1)) & 1 == 1 for p in packed, j in 1:width])

"""
    apply_linear_all(mat)

Images of all 2^d vectors under v -> v mat, as a packed `UInt32` array indexed by v + 1.
"""
function apply_linear_all(mat::AbstractMatrix)
    d = size(mat, 1)
    rows = UInt32.(pack_rows(mat))
    img = zeros(UInt32, 1 << d)
    for j in 0:d-1
        @inbounds for v in 0:(1<<j)-1
            img[(1<<j)+v+1] = img[v+1] ⊻ rows[j+1]
        end
    end
    return img
end

"""
    orbits(gens, d)

Orbit label of every vector of GF(2)^d under ⟨gens⟩, indexed by v + 1; the label is the smallest packed vector
of the orbit. Union-find with the smaller root kept, then path compression.
"""
function orbits(gens, d::Integer)
    n = 1 << d
    parent = collect(UInt32(0):UInt32(n - 1))
    @inline function root(x)
        @inbounds while parent[x+1] != x
            parent[x+1] = parent[parent[x+1]+1]
            x = parent[x+1]
        end
        return x
    end
    for g in gens
        img = apply_linear_all(g)
        @inbounds for v in UInt32(0):UInt32(n - 1)
            a, b = root(v), root(img[v+1])
            a == b && continue
            a < b ? (parent[b+1] = a) : (parent[a+1] = b)
        end
    end
    return UInt32[root(UInt32(v)) for v in 0:n-1]
end

"""
    closure(gens; cap=5_000_000) -> (order, elements or nothing, complete)

BFS closure of ⟨gens⟩ (exact order below `cap`).
"""
function closure(gens; cap::Integer=5_000_000)
    d = size(first(gens), 1)
    gp = [pack_rows(g) for g in gens]
    ident = pack_rows(GF2Mat(I(d)))
    seen = Set{Vector{UInt64}}([ident])
    frontier = [ident]
    allel = [ident]
    while !isempty(frontier)
        new = Vector{UInt64}[]
        for f in frontier, g in gp
            p = _mul_packed(f, g)
            p in seen || (push!(seen, p); push!(new, p))
        end
        length(seen) > cap && return length(seen), nothing, false
        frontier = new
        append!(allel, new)
    end
    return length(seen), allel, true
end

# packed rows of a * b over GF(2)
function _mul_packed(a::Vector{UInt64}, b::Vector{UInt64})
    out = zeros(UInt64, length(a))
    for (i, r) in enumerate(a)
        acc = UInt64(0)
        j = 1
        while r != 0
            isodd(r) && (acc ⊻= b[j])
            r >>= 1
            j += 1
        end
        out[i] = acc
    end
    return out
end

"""
    orbit_of(gens, v0, d)

Sorted BFS orbit of one packed vector (an independent check of [`orbits`](@ref)).
"""
function orbit_of(gens, v0::Integer, d::Integer)
    gp = [pack_rows(g) for g in gens]
    seen = Set{UInt64}([UInt64(v0)])
    frontier = [UInt64(v0)]
    while !isempty(frontier)
        nxt = UInt64[]
        for v in frontier, g in gp
            w = _mul_packed([v], g)[1]
            w in seen || (push!(seen, w); push!(nxt, w))
        end
        frontier = nxt
    end
    return sort!(collect(seen))
end

"""
    symplectic_group_order(k)

|Sp(2k, 2)| = 2^{k²} ∏_{i=1}^k (4^i − 1).
"""
symplectic_group_order(k::Integer) = big(2)^(k * k) * prod(big(4)^i - 1 for i in 1:k; init=big(1))

