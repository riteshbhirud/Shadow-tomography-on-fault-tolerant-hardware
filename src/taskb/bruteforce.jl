# Brute-force validation of the shadow-norm formula on small logical systems.
#
# Independent of the orbit / symplectic code: the group is enumerated as signed QuantumClifford tableaux built
# from gate circuits, the state is a dense Haar-random vector, outcomes are sampled from the Born rule and the
# classical-shadow estimator of Bu et al. is applied:
#   U = F g (F a uniform Pauli frame, g uniform in G), readout Z or X (Hᵏ before Z),
#   ô = s (-1)^{b·z} / λ_P  if U P U† = s Z^z, else 0.
# Dense states are little-endian: qubit q is bit q of the basis index.
# Random draws use numpy's default_rng so seeded runs reproduce the stored test samples.

"""
    circuit_clifford(gates, k)

The signed tableau of a gate list on `k` qubits.
"""
circuit_clifford(gates, k::Integer) = then_gates!(one(CliffordOperator, k), gates)

# c followed by the gates. The tableau rows go through the gates as a Stabilizer because in QuantumClifford
# 0.11.8 apply!(::CliffordOperator, op) with symbolic gates loses signs (S then S does not give Z).
function then_gates!(c::CliffordOperator, gates)
    s = Stabilizer(QuantumClifford.tab(c))
    for g in expand_gates(gates)
        apply!(s, _qc_op(g))
    end
    QuantumClifford.tab(c) === QuantumClifford.tab(s) || (QuantumClifford.tab(c) .= QuantumClifford.tab(s))
    return c
end

"""
    enumerate_group(gen_circuits, k; cap=200_000) -> (tableaux, words)

All signed tableaux of the group generated by the circuits (BFS), each with a word of generator indices whose
circuits, applied in order, give it.
"""
function enumerate_group(gen_circuits, k::Integer; cap::Integer=200_000)
    ident = one(CliffordOperator, k)
    seen = Dict(ident => Int[])
    order = [ident]
    frontier = [ident]
    while !isempty(frontier)
        nxt = typeof(ident)[]
        for t in frontier, gi in eachindex(gen_circuits)
            u = then_gates!(copy(t), gen_circuits[gi])
            haskey(seen, u) && continue
            seen[u] = [seen[t]; gi]
            push!(order, u)
            push!(nxt, u)
            length(seen) > cap && error("group too large for brute force")
        end
        frontier = nxt
    end
    return order, [seen[t] for t in order]
end

"""
    conjugate(c, p)

U P U† for the Clifford `c` (sign tracked).
"""
conjugate(c::CliffordOperator, p::PauliOperator) = apply!(Stabilizer([p]), c)[1]

"""
    tableau_symplectic(c)

Row convention: row q is the image of X_q, row k+q the image of Z_q, as (x|z).
"""
function tableau_symplectic(c::CliffordOperator)
    k = nqubits(c)
    m = zeros(Bool, 2k, 2k)
    t = QuantumClifford.tab(c)
    for r in 1:2k
        m[r, :] = [xbit(t[r]); zbit(t[r])]
    end
    return m
end

"""
    pauli_from_vec(v, k)

Pauli (sign +) of a packed (x|z) vector.
"""
pauli_from_vec(v::Integer, k::Integer) =
    PauliOperator(0x0, [isodd(v >> q) for q in 0:k-1], [isodd(v >> (k + q)) for q in 0:k-1])

"""
    exact_lambda(group, k, readout="Z")

λ_P for all 4ᵏ vectors by direct enumeration over the group (no orbit argument).
"""
function exact_lambda(group, k::Integer, readout::AbstractString="Z")
    lam = zeros(1 << 2k)
    for v in 0:(1<<2k)-1
        p = pauli_from_vec(v, k)
        cnt = 0
        for t in group
            q = conjugate(t, p)
            cnt += readout == "Z" ? !any(xbit(q)) : !any(zbit(q))
        end
        lam[v+1] = cnt / length(group)
    end
    return lam
end

"""
    numpy_rng(seed)

numpy's `default_rng(seed)` through PythonCall.
"""
numpy_rng(seed::Integer) = pymodule(:numpy).random.default_rng(seed)

"""
    haar_state(k, rng)

Haar-random k-qubit state vector from the numpy generator `rng` (Gaussian real and imaginary parts,
normalised).
"""
function haar_state(k::Integer, rng::Py)
    np = pymodule(:numpy)
    re = pyconvert(Vector{Float64}, rng.normal(; size=1 << k))
    imp = pyconvert(Vector{Float64}, rng.normal(; size=1 << k))
    psi = np.asarray(complex.(re, imp))
    # numpy's complex division by the norm can differ in the last bit from dividing both parts, so let numpy do it
    return pyconvert(Vector{ComplexF64}, np.divide(psi, np.linalg.norm(psi)))
end

# dense gate action on a little-endian state vector
function _apply_dense!(psi::Vector{ComplexF64}, g::Gate)
    q = g.qubits
    bit(i, j) = isodd(i >> j)
    n = length(psi)
    if g.name == :H
        for i in 0:n-1
            bit(i, q[1]) && continue
            j = i | (1 << q[1])
            a, b = psi[i+1], psi[j+1]
            psi[i+1], psi[j+1] = (a + b) / sqrt(2), (a - b) / sqrt(2)
        end
    elseif g.name == :S
        for i in 0:n-1
            bit(i, q[1]) && (psi[i+1] *= im)
        end
    elseif g.name == :Z
        for i in 0:n-1
            bit(i, q[1]) && (psi[i+1] = -psi[i+1])
        end
    elseif g.name == :X || g.name == :Y
        for i in 0:n-1
            bit(i, q[1]) && continue
            j = i | (1 << q[1])
            a, b = psi[i+1], psi[j+1]
            psi[i+1], psi[j+1] = g.name == :X ? (b, a) : (-im * b, im * a)
        end
    elseif g.name == :CZ
        for i in 0:n-1
            bit(i, q[1]) && bit(i, q[2]) && (psi[i+1] = -psi[i+1])
        end
    elseif g.name == :CX || g.name == :SWAP
        out = copy(psi)
        for i in 0:n-1
            j = if g.name == :CX
                bit(i, q[1]) ? i ⊻ (1 << q[2]) : i
            else
                bit(i, q[1]) == bit(i, q[2]) ? i : i ⊻ (1 << q[1]) ⊻ (1 << q[2])
            end
            out[j+1] = psi[i+1]
        end
        psi .= out
    else
        error("unknown gate $(g.name)")
    end
    return psi
end

"""
    apply_dense(gates, psi)

The state after the gate list (a new vector).
"""
function apply_dense(gates, psi::AbstractVector)
    out = Vector{ComplexF64}(psi)
    for g in expand_gates(gates)
        _apply_dense!(out, g)
    end
    return out
end

"""
    circuit_unitary(gates, k)

Dense unitary of a gate list (columns are images of basis states).
"""
circuit_unitary(gates, k::Integer) =
    reduce(hcat, [apply_dense(gates, [i == j ? 1.0 + 0im : 0im for i in 0:(1<<k)-1]) for j in 0:(1<<k)-1])

"""
    expval(psi, p)

⟨ψ|P|ψ⟩ for a Hermitian Pauli `p` (sign included).
"""
function expval(psi::AbstractVector, p::PauliOperator)
    k = nqubits(p)
    gates = Gate[]
    for q in 0:k-1
        x, z = p[q+1]
        x && z ? push!(gates, Gate(:Y, [q])) : x ? push!(gates, Gate(:X, [q])) : z ? push!(gates, Gate(:Z, [q])) : nothing
    end
    s = p.phase[] == 0x0 ? 1 : p.phase[] == 0x2 ? -1 : error("non-Hermitian Pauli")
    return s * real(dot(psi, apply_dense(gates, psi)))
end

"""
    simulate_estimator(group, words, gen_circuits, psi, paulis, lam, k, shots, rng; readout="Z")

Single-shot estimates (length(paulis) × shots) of the native classical shadow; `lam[v+1]` is λ_P of the
packed Pauli v for the readout used ("Z", "X" or "mix", which picks Z or X with probability 1/2 per shot).
`rng` is a numpy generator ([`numpy_rng`](@ref)).
"""
function simulate_estimator(group, words, gen_circuits, psi, paulis, lam, k::Integer, shots::Integer, rng;
                            readout::AbstractString="Z")
    hall = [Gate(:H, [q]) for q in 0:k-1]
    est = zeros(length(paulis), shots)
    ps = [pauli_from_vec(v, k) for v in paulis]
    np = pymodule(:numpy)
    for s in 1:shots
        # draw order per shot: group element, Pauli frame, readout basis, outcome
        gi = pyconvert(Int, rng.integers(length(group))) + 1
        fv = pyconvert(Int, rng.integers(1 << 2k))
        rb = readout in ("Z", "X") ? readout : (pyconvert(Float64, rng.random()) < 0.5 ? "Z" : "X")
        frame = Gate[]
        for q in 0:k-1
            isodd(fv >> q) && push!(frame, Gate(:X, [q]))
            isodd(fv >> (k + q)) && push!(frame, Gate(:Z, [q]))
        end
        circ = [reduce(vcat, [gen_circuits[i] for i in words[gi]]; init=Gate[]); frame; rb == "X" ? hall : Gate[]]
        u = then_gates!(copy(group[gi]), [frame; rb == "X" ? hall : Gate[]])
        phi = apply_dense(circ, psi)
        prob = abs.(phi) .^ 2
        b = pyconvert(Int, rng.choice(1 << k; p=np.asarray(prob ./ np_sum(prob))))
        for (j, (v, p)) in enumerate(zip(paulis, ps))
            q = conjugate(u, p)
            any(xbit(q)) && continue
            sign = q.phase[] == 0x0 ? 1 : -1
            est[j, s] = sign * (-1)^count(q0 -> zbit(q)[q0+1] && isodd(b >> q0), 0:k-1) / lam[v+1]
        end
    end
    return est
end
